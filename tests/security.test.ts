import test from 'node:test'
import assert from 'node:assert/strict'
import { resolve } from 'node:path'
import { readFileSync } from 'node:fs'
import { rendererAsset, validatedDevURL, PRODUCTION_CSP } from '../src/main/security.ts'
const root = resolve('out/renderer')
test('custom protocol resolves only known renderer file types within root', () => {
  assert.equal(rendererAsset(root, 'geppio://app/')?.path, resolve(root, 'index.html'))
  assert.equal(rendererAsset(root, 'geppio://app/assets/app.js')?.mime, 'text/javascript; charset=utf-8')
  for (const value of ['file:///private/file.js', 'geppio://other/index.html', 'geppio://user:pass@app/index.html', 'geppio://app:99/index.html', 'geppio://app/%2e%2e%2fprivate.js', 'geppio://app/%5cprivate.js', 'geppio://app/%00file.js', 'geppio://app/.env', 'geppio://app/assets/app.js.map', 'invalid']) assert.equal(rendererAsset(root, value), null, value)
})
test('development URL accepts only the configured loopback origin', () => {
  assert.equal(validatedDevURL('http://127.0.0.1:5173/'), 'http://127.0.0.1:5173/')
  for (const value of ['https://example.com', 'http://localhost:5173/', 'http://127.0.0.1:6000', 'http://evil@127.0.0.1:5173']) assert.throws(() => validatedDevURL(value))
})
test('production script CSP is not the development inline-script policy', () => {
  assert.match(PRODUCTION_CSP, /script-src 'self';/)
  assert.match(PRODUCTION_CSP, /connect-src 'none'/)
  assert.ok(!PRODUCTION_CSP.includes('unsafe-eval'))
})
test('static security regression: renderer has only fixed management, activation-bound data and authorized window chrome', () => {
  const preload = readFileSync('src/preload/index.ts', 'utf8'), main = readFileSync('src/main/index.ts', 'utf8')
  assert.ok(!/child_process|node:fs|sendSync|\.send\(/.test(preload))
  assert.deepEqual([...preload.matchAll(/ipcRenderer.invoke\('([^']+)'/g)].map(match => match[1]), ['plugins:list', 'plugins:install', 'plugins:install-file', 'plugins:set-developer-mode', 'plugins:reload', 'plugins:link', 'plugins:set-enabled', 'plugins:remove', 'window:minimize', 'window:maximize', 'window:close', 'plugin-data:begin', 'plugin-data:read', 'plugin-data:write', 'plugin-data:end', 'document:open', 'document:save', 'document:reload', 'document:release', 'document:activate', 'document:close', 'explorer:select', 'explorer:list', 'explorer:open', 'explorer:release', 'explorer:create-file', 'explorer:create-directory', 'explorer:rename-file', 'terminal:read', 'terminal:start', 'terminal:input', 'terminal:resize', 'terminal:close', 'git:status', 'git:compare', 'git:stage', 'git:unstage', 'git:history', 'git:historyPage', 'git:historyCommit', 'git:historyCompare', 'search:start', 'search:read', 'search:cancel', 'search:open', 'workspace:read', 'workspace:readTools', 'workspace:restore', 'workspace:standalone', 'workspace:configure', 'workspace:forget', 'workspace:remember', 'portable-layout:import', 'portable-layout:export', 'quick-open:start', 'quick-open:read', 'quick-open:cancel', 'quick-open:open'])
  assert.doesNotMatch(readFileSync('sdk/plugin.d.ts', 'utf8'), /PortableLayoutBridge|portable-layout:/)
  const documents = readFileSync('src/main/document-bridge.ts', 'utf8')
  assert.match(documents, /event.sender !== win.webContents/)
  assert.match(documents, /frame !== win.webContents.mainFrame/)
  assert.match(documents, /frame\?\.url !== expectedURL/)
  assert.match(documents, /validDocumentRequest\(operation, args\)/)
  assert.match(documents, /validGitRequest\(operation, args\)/)
  assert.match(documents, /validSearchRequest\(operation, args\)/)
  assert.match(documents, /validQuickOpenRequest\(operation, args\)/)
  assert.match(documents, /validExplorerMutationRequest\(args\)/)
  assert.doesNotMatch(readFileSync('sdk/plugin.d.ts', 'utf8'), /explorer:(create-file|create-directory|rename-file)|ExplorerMutationResult/)
  assert.doesNotMatch(readFileSync('sdk/plugin.d.ts', 'utf8'), /QuickOpenBridge|quick-open:/)
  assert.doesNotMatch(readFileSync('sdk/plugin.d.ts', 'utf8'), /SearchBridge|search:(start|read|cancel|open)/)
  const terminal = readFileSync('src/main/terminal-bridge.ts', 'utf8')
  assert.match(terminal, /event.sender !== win.webContents/)
  assert.match(terminal, /event.senderFrame !== win.webContents.mainFrame/)
  assert.match(terminal, /event.senderFrame\?\.url !== expectedURL/)
  assert.match(terminal, /validTerminalRequest\(operation, args\)/)
  assert.doesNotMatch(readFileSync('sdk/plugin.d.ts', 'utf8'), /DocumentBridge|document:open|ExplorerBridge|explorer:|TerminalBridge|terminal:|GitBridge|git:status|git:compare|git:stage|git:unstage|git:history/)
  assert.match(main, /event.senderFrame !== event.sender.mainFrame/)
  assert.match(main, /sandbox: true/); assert.match(main, /contextIsolation: true/)
  assert.match(main, /nodeIntegration: false/); assert.match(main, /webviewTag: false/)
  assert.match(main, /nodeIntegrationInWorker: false/)
  assert.match(main, /const testData = !app.isPackaged \? process.env.GEPPIO_TEST_USER_DATA : undefined/)
  assert.match(main, /validatedTestProfile\(testData\)/)
  assert.match(main, /additionalArguments: testData && process.env.GEPPIO_TEST_DEMO_WIDGETS === '1'/)
  assert.match(PRODUCTION_CSP, /worker-src 'self'/)
})
